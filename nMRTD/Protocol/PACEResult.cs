using Org.BouncyCastle.Crypto;

using nMRTD.Lds;

namespace nMRTD.Protocol;

/// <summary>
/// Port of <c>org.jmrtd.protocol.PACEResult</c>: result of a PACE protocol run. Java's <c>Serializable</c>
/// marker is dropped per porting-conventions.md (no reflection-based serialization is needed in this
/// port). Java's <c>KeyPair</c>/<c>PublicKey</c> become BC's
/// <see cref="Org.BouncyCastle.Crypto.AsymmetricCipherKeyPair"/>/<see cref="AsymmetricKeyParameter"/>, per
/// the conventions already established throughout this port (see <c>Util.cs</c>'s and
/// <c>PACEGMMappingResult.cs</c>'s doc comments -- notably, <c>AsymmetricCipherKeyPair</c> does not
/// override <c>Equals</c>/<c>GetHashCode</c> either, so <see cref="PcdKeyPair"/> comparisons below are
/// reference-identity comparisons in both the Java original and this port).
/// </summary>
public class PACEResult
{
    /// <summary>The access key that was used.</summary>
    public IAccessKeySpec? PaceKey { get; }

    /// <summary>The mapping type, <c>GM</c>, <c>IM</c>, or <c>CAM</c>.</summary>
    public PACEInfo.MappingType? MappingType { get; }

    /// <summary>The agreement algorithm that was used in the PACE protocol run, <c>"DH"</c> or <c>"ECDH"</c>.</summary>
    public string? AgreementAlg { get; }

    /// <summary>The cipher algorithm that was reported in the PACE info.</summary>
    public string? CipherAlg { get; }

    /// <summary>The digest algorithm that was reported in the PACE info.</summary>
    public string? DigestAlg { get; }

    /// <summary>The key length that was reported in the PACE info.</summary>
    public int KeyLength { get; }

    /// <summary>The result of the mapping step.</summary>
    public PACEMappingResult? MappingResult { get; }

    /// <summary>The ephemeral key pair that was generated by the terminal (the PCD).</summary>
    public AsymmetricCipherKeyPair? PcdKeyPair { get; }

    /// <summary>The public key that was sent by the ICC (the chip, the PICC).</summary>
    public AsymmetricKeyParameter? PiccPublicKey { get; }

    /// <summary>The secure messaging wrapper that resulted from the PACE protocol run.</summary>
    public SecureMessagingWrapper? Wrapper { get; }

    /// <summary>The result of a PACE protocol run.</summary>
    /// <param name="paceKey">the access key</param>
    /// <param name="mappingType">the mapping type, <c>GM</c>, <c>IM</c>, or <c>CAM</c></param>
    /// <param name="agreementAlg">the agreement algorithm, <c>"DH"</c> or <c>"ECDH"</c></param>
    /// <param name="cipherAlg">the cipher algorithm</param>
    /// <param name="digestAlg">the digest algorithm</param>
    /// <param name="keyLength">the key length</param>
    /// <param name="mappingResult">the result of the mapping step</param>
    /// <param name="pcdKeyPair">the key pair generated by the PCD</param>
    /// <param name="piccPublicKey">the public key sent by the PICC</param>
    /// <param name="wrapper">the resulting secure messaging wrapper</param>
    public PACEResult(
        IAccessKeySpec? paceKey,
        PACEInfo.MappingType? mappingType,
        string? agreementAlg,
        string? cipherAlg,
        string? digestAlg,
        int keyLength,
        PACEMappingResult? mappingResult,
        AsymmetricCipherKeyPair? pcdKeyPair,
        AsymmetricKeyParameter? piccPublicKey,
        SecureMessagingWrapper? wrapper)
    {
        PaceKey = paceKey;
        MappingType = mappingType;
        AgreementAlg = agreementAlg;
        CipherAlg = cipherAlg;
        DigestAlg = digestAlg;
        KeyLength = keyLength;
        MappingResult = mappingResult;
        PcdKeyPair = pcdKeyPair;
        PiccPublicKey = piccPublicKey;
        Wrapper = wrapper;
    }

    /// <summary>Returns a textual representation of this PACE result.</summary>
    /// <returns>a textual representation of this PACE result</returns>
    public override string ToString() =>
        "PACEResult ["
        + $"paceKey: {PaceKey}"
        + $", mappingType: {MappingType}"
        + $", agreementAlg: {AgreementAlg}"
        + $", cipherAlg: {CipherAlg}"
        + $", digestAlg: {DigestAlg}"
        + $", keyLength: {KeyLength}"
        + $", mappingResult: {MappingResult}"
        + $", piccPublicKey: {Util.GetDetailedPublicKeyAlgorithm(PiccPublicKey)}"
        /* NOTE: preserved Java quirk -- the original unconditionally calls pcdKeyPair.getPrivate()/
         * .getPublic(), which throws a NullPointerException if pcdKeyPair is null. The null-forgiving
         * operators below reproduce that: a null PcdKeyPair throws NullReferenceException here too,
         * rather than being silently tolerated. */
        + $", pcdPrivateKey: {Util.GetDetailedPrivateKeyAlgorithm(PcdKeyPair!.Private)}"
        + $", pcdPublicKey: {Util.GetDetailedPublicKeyAlgorithm(PcdKeyPair!.Public)}";

    public override int GetHashCode()
    {
        const int prime = 1991;
        int result = 11;
        result = (prime * result) + (PaceKey?.GetHashCode() ?? 0);
        result = (prime * result) + (AgreementAlg?.GetHashCode() ?? 0);
        result = (prime * result) + (CipherAlg?.GetHashCode() ?? 0);
        result = (prime * result) + (DigestAlg?.GetHashCode() ?? 0);
        result = (prime * result) + (MappingResult?.GetHashCode() ?? 0);
        result = (prime * result) + KeyLength;
        result = (prime * result) + (MappingType?.GetHashCode() ?? 0);
        result = (prime * result) + (PcdKeyPair?.GetHashCode() ?? 0);
        result = (prime * result) + (PiccPublicKey?.GetHashCode() ?? 0);
        result = (prime * result) + (Wrapper?.GetHashCode() ?? 0);
        return result;
    }

    public override bool Equals(object? obj)
    {
        if (ReferenceEquals(this, obj))
        {
            return true;
        }

        if (obj is null || GetType() != obj.GetType())
        {
            return false;
        }

        var other = (PACEResult)obj;
        return Equals(PaceKey, other.PaceKey)
            && string.Equals(AgreementAlg, other.AgreementAlg, StringComparison.Ordinal)
            && string.Equals(CipherAlg, other.CipherAlg, StringComparison.Ordinal)
            && string.Equals(DigestAlg, other.DigestAlg, StringComparison.Ordinal)
            && Equals(MappingResult, other.MappingResult)
            && KeyLength == other.KeyLength
            && MappingType == other.MappingType
            && Equals(PcdKeyPair, other.PcdKeyPair)
            && Equals(PiccPublicKey, other.PiccPublicKey)
            && Equals(Wrapper, other.Wrapper);
    }
}
