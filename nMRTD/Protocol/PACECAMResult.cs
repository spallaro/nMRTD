using Org.BouncyCastle.Crypto;

using nMRTD.Lds;
using nMRTD.SmartCards;

namespace nMRTD.Protocol;

/// <summary>
/// Port of <c>org.jmrtd.protocol.PACECAMResult</c>: the result of a PACE-CAM (Chip Authentication
/// Mapping) protocol execution.
/// </summary>
public sealed class PACECAMResult : PACEResult
{
    private readonly byte[]? _encryptedChipAuthenticationData;
    private readonly byte[]? _chipAuthenticationData;

    /// <summary>Constructs a result.</summary>
    /// <param name="paceKey">the static PACE key (derived from MRZ, CAN, PIN, or PUK)</param>
    /// <param name="agreementAlg">the agreement algorithm that was used</param>
    /// <param name="cipherAlg">the cipher algorithm that was used</param>
    /// <param name="digestAlg">the digest algorithm that was used</param>
    /// <param name="keyLength">the key length that was used</param>
    /// <param name="mappingResult">the result from the mapping step</param>
    /// <param name="pcdKeyPair">the key-pair generated by the PCD</param>
    /// <param name="piccPublicKey">the public key sent by the chip</param>
    /// <param name="encryptedChipAuthenticationData">the encrypted Chip Authentication data sent by the PICC</param>
    /// <param name="chipAuthenticationData">the decrypted Chip Authentication data</param>
    /// <param name="wrapper">the secure messaging wrapper that resulted</param>
    public PACECAMResult(
        IAccessKeySpec? paceKey,
        string? agreementAlg,
        string? cipherAlg,
        string? digestAlg,
        int keyLength,
        PACEMappingResult? mappingResult,
        AsymmetricCipherKeyPair? pcdKeyPair,
        AsymmetricKeyParameter? piccPublicKey,
        byte[]? encryptedChipAuthenticationData,
        byte[]? chipAuthenticationData,
        SecureMessagingWrapper? wrapper)
        : base(paceKey, PACEInfo.MappingType.CAM, agreementAlg, cipherAlg, digestAlg, keyLength, mappingResult, pcdKeyPair, piccPublicKey, wrapper)
    {
        _encryptedChipAuthenticationData = encryptedChipAuthenticationData == null ? null : (byte[])encryptedChipAuthenticationData.Clone();
        _chipAuthenticationData = chipAuthenticationData == null ? null : (byte[])chipAuthenticationData.Clone();
    }

    /// <summary>Returns the encrypted Chip Authentication data.</summary>
    /// <returns>the encrypted Chip Authentication data</returns>
    public byte[]? GetEncryptedChipAuthenticationData() =>
        _encryptedChipAuthenticationData == null ? null : (byte[])_encryptedChipAuthenticationData.Clone();

    /// <summary>Returns the result of decrypting the encrypted Chip Authentication data.</summary>
    /// <returns>the decrypted Chip Authentication data</returns>
    public byte[]? GetChipAuthenticationData() =>
        _chipAuthenticationData == null ? null : (byte[])_chipAuthenticationData.Clone();

    public override int GetHashCode()
    {
        const int prime = 31;
        int result = base.GetHashCode();
        result = (prime * result) + ArrayHashCode(_chipAuthenticationData);
        result = (prime * result) + ArrayHashCode(_encryptedChipAuthenticationData);
        return result;
    }

    public override bool Equals(object? obj)
    {
        if (ReferenceEquals(this, obj))
        {
            return true;
        }

        if (!base.Equals(obj))
        {
            return false;
        }

        if (GetType() != obj!.GetType())
        {
            return false;
        }

        var other = (PACECAMResult)obj;
        return ArraysEqual(_chipAuthenticationData, other._chipAuthenticationData)
            && ArraysEqual(_encryptedChipAuthenticationData, other._encryptedChipAuthenticationData);
    }

    public override string ToString() =>
        "PACECAMResult ["
        + $"paceKey: {PaceKey}, "
        + $"mappingType: {MappingType}, "
        + $"agreementAlg: {AgreementAlg}, "
        + $"cipherAlg: {CipherAlg}, "
        + $"digestAlg: {DigestAlg}, "
        + $"keyLength: {KeyLength}, "
        + $"mappingResult: {MappingResult}, "
        /* NOTE: preserved Java quirk -- unlike the base PACEResult.ToString() (which uses
         * Util.GetDetailedPrivateKeyAlgorithm/GetDetailedPublicKeyAlgorithm for key fields), this override
         * prints PcdKeyPair/PiccPublicKey via their own ToString(). Neither AsymmetricCipherKeyPair nor
         * (in the Java original) java.security.KeyPair overrides ToString(), so this yields an
         * uninformative default type-name string for pcdKeyPair -- an upstream JMRTD inconsistency, not
         * "fixed" per this port's quirk-preservation policy. */
        + $"pcdKeyPair: {PcdKeyPair}, "
        + $"piccPublicKey: {PiccPublicKey}, "
        + $"encryptedChipAuthenticationData: {ToHexOrDash(_encryptedChipAuthenticationData)}, "
        + $"wrapper: {Wrapper}, "
        + $"chipAuthenticationData: {ToHexOrDash(_chipAuthenticationData)}]";

    /// <summary>
    /// Renders a (possibly <c>null</c>) byte array as hex, or <c>"-"</c> when <c>null</c> -- mirrors the
    /// null-safety already used elsewhere in this port's <c>Result</c>-style <c>ToString</c> methods (see
    /// <c>AAResult.cs</c>), since <see cref="Hex.BytesToHexString"/> (unlike scuba's Java original) throws
    /// on a <c>null</c> argument.
    /// </summary>
    private static string ToHexOrDash(byte[]? bytes) => bytes == null ? "-" : Hex.BytesToHexString(bytes);

    /// <summary>
    /// Java-style <c>Arrays.hashCode</c> for a (possibly <c>null</c>) byte array. Fix: <c>PACECAMResult</c>
    /// extends <see cref="PACEResult"/>, not <see cref="PACEMappingResult"/> (which is where this helper's
    /// counterpart lives, shared by the GM/IM mapping-result subclasses) -- so it needs its own private copy,
    /// matching the pattern already established by <c>AAResult.cs</c>.
    /// </summary>
    private static int ArrayHashCode(byte[]? array)
    {
        if (array == null)
        {
            return 0;
        }

        int result = 1;
        foreach (byte b in array)
        {
            result = (31 * result) + (sbyte)b;
        }

        return result;
    }

    /// <summary>Java-style <c>Arrays.equals</c> for (possibly <c>null</c>) byte arrays. See <see cref="ArrayHashCode"/>'s doc comment.</summary>
    private static bool ArraysEqual(byte[]? a, byte[]? b)
    {
        if (a == null || b == null)
        {
            return a == b;
        }

        return a.AsSpan().SequenceEqual(b);
    }
}
