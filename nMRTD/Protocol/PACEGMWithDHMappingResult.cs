using Org.BouncyCastle.Crypto;

namespace nMRTD.Protocol;

/// <summary>
/// Port of <c>org.jmrtd.protocol.PACEGMWithDHMappingResult</c>: the result of the PACE nonce mapping step
/// in Generic Mapping with Diffie-Hellman setting.
/// </summary>
public sealed class PACEGMWithDHMappingResult : PACEGMMappingResult
{
    private readonly byte[]? _sharedSecret;

    /// <summary>Constructs a result.</summary>
    /// <param name="staticParameters">the static parameters</param>
    /// <param name="piccNonce">the nonce that was sent by the PICC</param>
    /// <param name="piccMappingPublicKey">the mapping public key sent by the PICC</param>
    /// <param name="pcdMappingKeyPair">the key-pair generated by the PCD</param>
    /// <param name="sharedSecret">the shared secret that was derived</param>
    /// <param name="ephemeralParameters">the ephemeral parameters that were derived</param>
    public PACEGMWithDHMappingResult(
        object? staticParameters,
        byte[]? piccNonce,
        AsymmetricKeyParameter? piccMappingPublicKey,
        AsymmetricCipherKeyPair? pcdMappingKeyPair,
        byte[]? sharedSecret,
        object? ephemeralParameters)
        : base(staticParameters, piccNonce, piccMappingPublicKey, pcdMappingKeyPair, ephemeralParameters)
    {
        _sharedSecret = sharedSecret == null ? null : (byte[])sharedSecret.Clone();
    }

    /// <summary>Returns the shared secret that was derived during this protocol step.</summary>
    /// <returns>the shared secret</returns>
    public byte[]? GetSharedSecret() => _sharedSecret == null ? null : (byte[])_sharedSecret.Clone();

    public override int GetHashCode()
    {
        const int prime = 31;
        int result = base.GetHashCode();
        result = (prime * result) + ArrayHashCode(_sharedSecret);
        return result;
    }

    public override bool Equals(object? obj)
    {
        if (ReferenceEquals(this, obj))
        {
            return true;
        }

        if (!base.Equals(obj))
        {
            return false;
        }

        if (GetType() != obj!.GetType())
        {
            return false;
        }

        var other = (PACEGMWithDHMappingResult)obj;
        return ArraysEqual(_sharedSecret, other._sharedSecret);
    }
}
