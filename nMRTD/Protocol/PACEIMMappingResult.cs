namespace nMRTD.Protocol;

/// <summary>
/// Port of <c>org.jmrtd.protocol.PACEIMMappingResult</c>: the result of the PACE nonce mapping step in an
/// Integrated Mapping setting.
/// </summary>
public sealed class PACEIMMappingResult : PACEMappingResult
{
    private readonly byte[]? _pcdNonce;

    /// <summary>Constructs a result.</summary>
    /// <param name="staticParameters">the static parameters</param>
    /// <param name="piccNonce">the nonce sent by the PICC</param>
    /// <param name="pcdNonce">the nonce generated by the PCD</param>
    /// <param name="ephemeralParameters">the resulting ephemeral parameters</param>
    public PACEIMMappingResult(object? staticParameters, byte[]? piccNonce, byte[]? pcdNonce, object? ephemeralParameters)
        : base(staticParameters, piccNonce, ephemeralParameters)
    {
        _pcdNonce = pcdNonce == null ? null : (byte[])pcdNonce.Clone();
    }

    /// <summary>Returns the nonce generated by the PCD.</summary>
    /// <returns>the nonce generated by the PCD</returns>
    public byte[]? GetPcdNonce() => _pcdNonce == null ? null : (byte[])_pcdNonce.Clone();

    public override int GetHashCode()
    {
        const int prime = 31;
        int result = base.GetHashCode();
        result = (prime * result) + ArrayHashCode(_pcdNonce);
        return result;
    }

    public override bool Equals(object? obj)
    {
        if (ReferenceEquals(this, obj))
        {
            return true;
        }

        if (!base.Equals(obj))
        {
            return false;
        }

        if (GetType() != obj!.GetType())
        {
            return false;
        }

        var other = (PACEIMMappingResult)obj;
        return ArraysEqual(_pcdNonce, other._pcdNonce);
    }
}
