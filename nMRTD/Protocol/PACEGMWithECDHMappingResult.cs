using Org.BouncyCastle.Crypto;
using Org.BouncyCastle.Math.EC;

using BigInteger = Org.BouncyCastle.Math.BigInteger;

namespace nMRTD.Protocol;

/// <summary>
/// Port of <c>org.jmrtd.protocol.PACEGMWithECDHMappingResult</c>: the result of the PACE nonce mapping
/// step in Generic Mapping with Elliptic Curve Diffie-Hellman setting.
///
/// Java stores only the affine X/Y coordinates of the shared secret point (as plain
/// <c>java.math.BigInteger</c>s), not a curve-bound point object -- <c>java.security.spec.ECPoint</c> is
/// itself already just a curve-agnostic (X, Y) value holder. This port follows the same design already
/// established by <c>Util.Os2ECPoint</c> (see its doc comment): the constructor accepts a curve-bound BC
/// <see cref="Org.BouncyCastle.Math.EC.ECPoint"/> (mirroring the Java constructor's <c>ECPoint</c>
/// parameter conceptually -- both are "the point that was computed"), extracts its normalized affine
/// coordinates for storage, and <see cref="GetSharedSecretPoint"/> hands back a curve-agnostic
/// <c>(BigInteger X, BigInteger Y)</c> tuple rather than reconstructing a BC point (which would require a
/// curve this stored representation was never given).
/// </summary>
public sealed class PACEGMWithECDHMappingResult : PACEGMMappingResult
{
    private readonly BigInteger? _sharedSecretPointX;
    private readonly BigInteger? _sharedSecretPointY;

    /// <summary>Constructs a result.</summary>
    /// <param name="staticParameters">the static parameters</param>
    /// <param name="piccNonce">the nonce that was sent by the PICC</param>
    /// <param name="piccMappingPublicKey">the mapping public key sent by the PICC</param>
    /// <param name="pcdMappingKeyPair">the key-pair generated by the PCD</param>
    /// <param name="sharedSecretPoint">the shared secret point that was derived</param>
    /// <param name="ephemeralParameters">the ephemeral parameters that were derived</param>
    public PACEGMWithECDHMappingResult(
        object? staticParameters,
        byte[]? piccNonce,
        AsymmetricKeyParameter? piccMappingPublicKey,
        AsymmetricCipherKeyPair? pcdMappingKeyPair,
        ECPoint sharedSecretPoint,
        object? ephemeralParameters)
        : base(staticParameters, piccNonce, piccMappingPublicKey, pcdMappingKeyPair, ephemeralParameters)
    {
        ArgumentNullException.ThrowIfNull(sharedSecretPoint);

        /* NOTE: java.security.spec.ECPoint.getAffineX()/getAffineY() are plain field getters -- that type
         * is always already in affine form. BC's ECPoint can be in projective/Jacobian form, so it is
         * normalized here defensively before extracting coordinates (a no-op for an already-affine point). */
        ECPoint normalized = sharedSecretPoint.Normalize();
        _sharedSecretPointX = normalized.AffineXCoord.ToBigInteger();
        _sharedSecretPointY = normalized.AffineYCoord.ToBigInteger();
    }

    /// <summary>Returns the shared secret point that was derived during this step.</summary>
    /// <returns>the affine X and Y coordinates of the shared secret point</returns>
    public (BigInteger? X, BigInteger? Y) GetSharedSecretPoint() => (_sharedSecretPointX, _sharedSecretPointY);

    public override int GetHashCode()
    {
        const int prime = 31;
        int result = base.GetHashCode();
        result = (prime * result)
            + (_sharedSecretPointX?.GetHashCode() ?? 0)
            + (_sharedSecretPointY?.GetHashCode() ?? 0);

        return result;
    }

    public override bool Equals(object? obj)
    {
        if (ReferenceEquals(this, obj))
        {
            return true;
        }

        if (!base.Equals(obj))
        {
            return false;
        }

        if (GetType() != obj!.GetType())
        {
            return false;
        }

        var other = (PACEGMWithECDHMappingResult)obj;
        return Equals(_sharedSecretPointX, other._sharedSecretPointX)
            && Equals(_sharedSecretPointY, other._sharedSecretPointY);
    }
}
