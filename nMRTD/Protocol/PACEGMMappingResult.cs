using Org.BouncyCastle.Crypto;

namespace nMRTD.Protocol;

/// <summary>
/// Port of <c>org.jmrtd.protocol.PACEGMMappingResult</c>: the result of the PACE nonce mapping step in
/// Generic Mapping setting. Java's <c>KeyPair</c> becomes BC's
/// <see cref="Org.BouncyCastle.Crypto.AsymmetricCipherKeyPair"/> (which, like Java's
/// <c>java.security.KeyPair</c>, does not override <c>Equals</c>/<c>GetHashCode</c> -- both use plain
/// reference identity, so <see cref="PcdMappingKeyPair"/> comparisons below are identity comparisons in
/// both the Java original and this port). Java's <c>PublicKey</c> becomes BC's
/// <see cref="AsymmetricKeyParameter"/>, per the convention already established throughout this port (see
/// <c>Util.cs</c>'s doc comment).
/// </summary>
public abstract class PACEGMMappingResult : PACEMappingResult
{
    /// <summary>The mapping public key that was sent by the PICC.</summary>
    public AsymmetricKeyParameter? PiccMappingPublicKey { get; }

    /// <summary>The mapping key-pair generated by the PCD.</summary>
    public AsymmetricCipherKeyPair? PcdMappingKeyPair { get; }

    /// <summary>Constructs a result.</summary>
    /// <param name="staticParameters">the static parameters</param>
    /// <param name="piccNonce">the nonce that was sent by the PICC</param>
    /// <param name="piccMappingPublicKey">the mapping public key sent by the PICC</param>
    /// <param name="pcdMappingKeyPair">the key-pair generated by the PCD</param>
    /// <param name="ephemeralParameters">the ephemeral parameters that were derived</param>
    protected PACEGMMappingResult(
        object? staticParameters,
        byte[]? piccNonce,
        AsymmetricKeyParameter? piccMappingPublicKey,
        AsymmetricCipherKeyPair? pcdMappingKeyPair,
        object? ephemeralParameters)
        : base(staticParameters, piccNonce, ephemeralParameters)
    {
        PiccMappingPublicKey = piccMappingPublicKey;
        PcdMappingKeyPair = pcdMappingKeyPair;
    }

    public override int GetHashCode()
    {
        const int prime = 31;
        int result = base.GetHashCode();
        result = (prime * result) + (PiccMappingPublicKey?.GetHashCode() ?? 0);

        /* NOTE: preserved JMRTD quirk -- PcdMappingKeyPair participates in Equals below but is not mixed
         * into GetHashCode here (upstream Java bug: violates the hashCode/equals contract). Not "fixed"
         * per this port's quirk-preservation policy. */
        return result;
    }

    public override bool Equals(object? obj)
    {
        if (ReferenceEquals(this, obj))
        {
            return true;
        }

        if (!base.Equals(obj))
        {
            return false;
        }

        if (GetType() != obj!.GetType())
        {
            return false;
        }

        var other = (PACEGMMappingResult)obj;
        return Equals(PiccMappingPublicKey, other.PiccMappingPublicKey)
            && Equals(PcdMappingKeyPair, other.PcdMappingKeyPair);
    }
}
