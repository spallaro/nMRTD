    [Fact]
    public void testReflexive()
    {
        CheckReflexive(CreateTestObject());
    }

    internal static void CheckReflexive(DG15File dg15File)
    {
        byte[] encoded = dg15File.GetEncoded()!;

        MemoryStream input = new MemoryStream(encoded);
        DG15File copy = new DG15File(input);

        Assert.Equal(dg15File, copy);
        Assert.Equal(dg15File.GetPublicKey(), copy.GetPublicKey());

        byte[] encodedCopy = copy.GetEncoded()!;
        Assert.Equal(Hex.BytesToHexString(encoded), Hex.BytesToHexString(encodedCopy));

    }

    [Fact]
    public void testGetPublic()
    {
        AsymmetricCipherKeyPair keyPair = CreateTestKeyPair();
        AsymmetricKeyParameter publicKey = keyPair.Public;
        DG15File dg15File = new DG15File(publicKey);
        AsymmetricKeyParameter? otherPublicKey = dg15File.GetPublicKey();
        Assert.Equal(publicKey, otherPublicKey);
    }

